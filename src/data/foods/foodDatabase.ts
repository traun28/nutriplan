/**
 * Part 7 — local food/meal dataset.
 *
 * DATASET NOTE
 * ------------
 * Nutrition figures are APPROXIMATE reference values chosen for an
 * educational college project. Real values vary with portion size,
 * brand, recipe, ingredients and cooking method. They are not
 * laboratory measurements and must not be treated as exact.
 *
 * SCHEMA (see FoodItemRecord in types/profile.ts)
 *   id                     stable machine id — never the display name
 *   name                   human-readable label
 *   category               primary meal slot
 *   alsoSuitableFor        extra slots the item fits
 *   dietaryTypes           patterns the item is compatible with
 *   calories/protein/carbs/fat   per ONE servingSize
 *   servingSize            { quantity, unit } reference portion
 *   ingredients            normalised lowercase names (conflict detection)
 *   allergens              ids from COMMON_ALLERGENS
 *   intoleranceFlags       ids from COMMON_INTOLERANCES
 *   tags / cuisines        ranking signals
 *   preparationTimeMinutes practical-constraint signal
 *   complexity             very_easy | easy | moderate | advanced
 *   min/maxServings        realistic portion bounds for scaling
 *
 * Dietary rule used throughout this project:
 *   vegetarian   = no meat, no fish, no eggs (dairy allowed)
 *   vegan        = no animal-derived ingredients at all
 *   eggetarian   = vegetarian + eggs
 *   pescatarian  = vegetarian + fish
 *   non_vegetarian = anything
 * An item lists EVERY pattern it is compatible with, so a plain dal is
 * tagged vegetarian, vegan, eggetarian, pescatarian and non_vegetarian.
 */
